-- ─────────────────────────── Admin allow-list ───────────────────────────
-- Being "authenticated" is NOT enough to write: if public sign-ups were ever
-- enabled, anyone could get an authenticated session with the public key.
-- Only users listed here may write.
create table if not exists public.admins (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;
grant execute on function public.is_admin() to anon, authenticated;

-- Today in Kerala (the server runs in UTC).
create or replace function public.today_ist()
returns date
language sql
stable
as $$ select (now() at time zone 'Asia/Kolkata')::date; $$;

-- ─────────────────────────────── Programs ───────────────────────────────
-- counts_as decides which public counter a program feeds:
--   'kits'  → "Kits given"     'meals' → "Foods distributed"     'other' → neither
create table if not exists public.programs (
  id          smallint generated by default as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name_en     text not null,
  name_ml     text not null default '',
  icon        text not null default 'plate',
  counts_as   text not null default 'other' check (counts_as in ('kits', 'meals', 'other')),
  sort_order  int  not null default 0,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

-- ───────────────────────────── Ledger entries ───────────────────────────
create table if not exists public.ledger_entries (
  id          uuid primary key default gen_random_uuid(),
  entry_date  date not null default public.today_ist(),
  quantity    int  not null check (quantity > 0 and quantity <= 1000000),
  place       text not null check (place = btrim(place) and length(place) between 1 and 120),
  program_id  smallint not null references public.programs (id) on delete restrict,
  note        text check (note is null or length(note) <= 500),
  photo_url   text,
  created_at  timestamptz not null default now(),
  created_by  uuid default auth.uid()
);
alter table public.ledger_entries add column if not exists photo_url text;
create index if not exists ledger_entries_date_idx    on public.ledger_entries (entry_date desc, created_at desc);
create index if not exists ledger_entries_program_idx on public.ledger_entries (program_id, entry_date desc);
create index if not exists ledger_entries_place_idx   on public.ledger_entries (place, entry_date desc);

