-- ═══════════════════════════ Impact statistics ══════════════════════════
-- The single source for every public counter. Computed in the database.
--   kits  = SUM(quantity) where program.counts_as = 'kits'
--   meals = SUM(quantity) where program.counts_as = 'meals'
--   days  = today (IST) − start, where start = settings.programme_start_date
--           if set, otherwise the earliest entry_date. Grows by itself daily.
create or replace function public.get_impact_stats()
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
  with
  e as (
    select le.quantity, le.entry_date, le.place, le.program_id, p.counts_as
    from ledger_entries le join programs p on p.id = le.program_id
  ),
  start as (
    select coalesce(
      (select nullif(value, '')::date from settings where key = 'programme_start_date'),
      (select min(entry_date) from ledger_entries)
    ) as d
  )
  select jsonb_build_object(
    'kits',          coalesce((select sum(quantity) from e where counts_as = 'kits'), 0),
    'meals',         coalesce((select sum(quantity) from e where counts_as = 'meals'), 0),
    'days',          (select case when d is null then null else greatest(0, today_ist() - d) end from start),
    'start_date',    (select d from start),
    'total_entries', (select count(*) from ledger_entries),
    'last_entry_at', (select max(created_at) from ledger_entries),
    'by_program', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', x.id, 'slug', x.slug, 'name_en', x.name_en, 'name_ml', x.name_ml,
               'icon', x.icon, 'counts_as', x.counts_as, 'total', x.total, 'entries', x.entries)
             order by x.sort_order, x.id)
      from (
        select p.id, p.slug, p.name_en, p.name_ml, p.icon, p.counts_as, p.sort_order,
               coalesce(sum(le.quantity), 0) as total, count(le.id) as entries
        from programs p left join ledger_entries le on le.program_id = p.id
        group by p.id
        having p.is_active or count(le.id) > 0
      ) x), '[]'::jsonb),
    'by_place', coalesce((
      select jsonb_agg(jsonb_build_object('place', place, 'total', total, 'entries', entries)
             order by total desc, place)
      from (select place, sum(quantity) as total, count(*) as entries from e group by place) y), '[]'::jsonb),
    'by_month', coalesce((
      select jsonb_agg(jsonb_build_object('month', month, 'kits', kits, 'meals', meals, 'other', other, 'total', total)
             order by month)
      from (
        select to_char(date_trunc('month', entry_date), 'YYYY-MM') as month,
               coalesce(sum(quantity) filter (where counts_as = 'kits'), 0)  as kits,
               coalesce(sum(quantity) filter (where counts_as = 'meals'), 0) as meals,
               coalesce(sum(quantity) filter (where counts_as = 'other'), 0) as other,
               sum(quantity) as total
        from e group by 1
      ) z), '[]'::jsonb)
  );
$$;
grant execute on function public.get_impact_stats() to anon, authenticated;

-- Drag-to-reorder for the video gallery. Runs with the caller's rights, so RLS
-- still decides: only the admin's update actually changes rows.
create or replace function public.reorder_videos(ids uuid[])
returns void
language sql
security invoker
set search_path = public
as $$
  update videos v set sort_order = x.ord
  from unnest(ids) with ordinality as x(id, ord)
  where v.id = x.id;
$$;
revoke execute on function public.reorder_videos(uuid[]) from anon;
grant execute on function public.reorder_videos(uuid[]) to authenticated;

