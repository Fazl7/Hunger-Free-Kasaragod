  release_date     date not null default public.today_ist(),
  place            text check (place is null or length(place) <= 120),
  meta_description text check (meta_description is null or length(meta_description) <= 320),
  is_published     boolean not null default false,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists press_public_idx on public.press_releases (is_published, release_date desc, created_at desc);

